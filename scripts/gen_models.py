"""Usage (from modules/foxglove-viewer): py -3 scripts/gen_models.py

The extension build has no loader for .glb files, so the models travel inside the bundle as a generated
TypeScript module. Rerun this whenever a file in assets/ changes (or MODELS below does) and commit both.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "models_data.ts"
CHUNK = 100  # short lines: one 250 KB line makes eslint and the build several times slower

# model id (the key used in src/models.ts) -> file in assets/
MODELS = {
    "CAR": "car_q.glb",
    "TRUCK": "truck_q.glb",
    "PEDESTRIAN": "mannequin_rs.glb",
    "MOTORCYCLE": "moto_alice.glb",
    "EGO": "suv_q.glb",
}

HEADER = """// Copyright (c) LT EPS. All Rights Reserved.
// Proprietary and Confidential.
// COMPONENT: FOXGLOVE_VIEWER
/// @file
/// @brief
///   GENERATED by scripts/gen_models.py from the files in assets/ (see assets/ASSETS.md). Do not edit.
/// @author Pavan Karimajji <Pavan.Karimajji@larsentoubro.com>

"""


def entry(name, filename):
    b64 = base64.b64encode((ROOT / "assets" / filename).read_bytes()).decode("ascii")
    lines = "".join(f'    "{b64[i:i + CHUNK]}",\n' for i in range(0, len(b64), CHUNK))
    return f"  // assets/{filename}\n  {name}: [\n{lines}  ].join(\"\"),\n"


def main():
    body = "".join(entry(name, filename) for name, filename in MODELS.items())
    OUT.write_text(f"{HEADER}export const MODEL_BASE64 = {{\n{body}}};\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes) from {len(MODELS)} models")


if __name__ == "__main__":
    main()
