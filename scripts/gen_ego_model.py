"""Usage (from modules/foxglove-viewer): py -3 scripts/gen_ego_model.py

The extension build has no loader for .glb files, so the model travels inside the bundle as a
generated TypeScript string. Rerun this whenever assets/ego_car.glb changes and commit both files.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "ego_car.glb"
OUT = ROOT / "src" / "ego_model_data.ts"
CHUNK = 100  # short lines: one 250 KB line makes eslint and the build several times slower

HEADER = """// Copyright (c) LT EPS. All Rights Reserved.
// Proprietary and Confidential.
// COMPONENT: FOXGLOVE_VIEWER
/// @file
/// @brief
///   GENERATED by scripts/gen_ego_model.py from assets/ego_car.glb (see assets/ASSETS.md). Do not edit.
/// @author Pavan Karimajji <Pavan.Karimajji@larsentoubro.com>

"""


def main():
    b64 = base64.b64encode(SRC.read_bytes()).decode("ascii")
    lines = "".join(f'  "{b64[i:i + CHUNK]}",\n' for i in range(0, len(b64), CHUNK))
    OUT.write_text(f'{HEADER}export const EGO_MODEL_BASE64 = [\n{lines}].join("");\n', encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes) from {SRC} ({SRC.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
